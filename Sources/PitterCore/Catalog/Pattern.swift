import Foundation

/// A pattern is an ordered list of scale-degree deltas applied cyclically
/// from a start note, bounded by a range, with reflect-at-the-edge semantics.
public struct Pattern: Hashable, Codable, Sendable, Identifiable {
    public enum Category: String, CaseIterable, Codable, Sendable, Hashable {
        case step       // runs by step
        case interval   // runs by a fixed skip interval (thirds … octaves)
        case arpeggio   // chord-shaped runs
    }
    
    /// Stable, e.g. "thirds"
    public let id: String
    /// Display name, e.g. "Thirds"
    public let name: String
    /// Category of the pattern
    public let category: Category
    /// Non-empty scale-degree deltas, applied cyclically
    public let deltas: [Int]
    
    /// Initialize a pattern with validation of deltas.
    /// - Precondition: deltas must be non-empty, every element nonzero, and sum > 0
    public init(id: String, name: String, category: Category, deltas: [Int]) {
        precondition(!deltas.isEmpty, "Pattern deltas must be non-empty")
        precondition(!deltas.contains(0), "Pattern deltas must not contain zero")
        precondition(deltas.reduce(0, +) > 0, "Pattern deltas must have positive sum")
        
        self.id = id
        self.name = name
        self.category = category
        self.deltas = deltas
    }
    
    /// The built-in catalog of patterns.
    public static let builtIns: [Pattern] = [
        Pattern(id: "seconds", name: "Seconds", category: .step, deltas: [1]),
        Pattern(id: "thirds", name: "Thirds", category: .interval, deltas: [2, -1]),
        Pattern(id: "fourths", name: "Fourths", category: .interval, deltas: [3, -2]),
        Pattern(id: "fifths", name: "Fifths", category: .interval, deltas: [4, -3]),
        Pattern(id: "sixths", name: "Sixths", category: .interval, deltas: [5, -4]),
        Pattern(id: "sevenths", name: "Sevenths", category: .interval, deltas: [6, -5]),
        Pattern(id: "octaves", name: "Octave displacement", category: .interval, deltas: [7, -6]),
        Pattern(id: "tonicArpeggio", name: "Tonic triad arpeggio", category: .arpeggio, deltas: [2, 2, 3]),
        Pattern(id: "diatonicTriads", name: "Diatonic triads", category: .arpeggio, deltas: [2, 2, 4])
    ]
    
    /// Generate a sequence of pitches using this pattern.
    /// - Parameters:
    ///   - scale: The scale to walk in
    ///   - start: The starting pitch
    ///   - low: The lower bound of pitches to include
    ///   - high: The upper bound of pitches to include
    /// - Returns: An array of pitches generated by the pattern
    public func generate(in scale: Scale, from start: Pitch, low: Pitch, high: Pitch) -> [Pitch] {
        // Precondition checks
        precondition(low.midiNumber <= high.midiNumber, "Low bound must not exceed high bound")
        precondition(low.midiNumber <= start.midiNumber && start.midiNumber <= high.midiNumber, "Start must be within bounds")
        precondition(scale.isInScale(start), "Start must be in the scale")
        
        // Anchor the start to the scale's own spelling
        let anchored = scale.nextUp(after: scale.nextDown(before: start))
        
        // Safety guard against non-terminating patterns
        let maxSteps = 8 * (high.midiNumber - low.midiNumber) * deltas.count + 64
        var steps = 0
        
        func step(_ pitch: Pitch, _ delta: Int) -> Pitch {
            steps += 1
            precondition(steps <= maxSteps, "Pattern: walk did not terminate")
            
            // Apply the delta to the pitch
            var current = pitch
            for _ in 0..<abs(delta) {
                if delta > 0 {
                    current = scale.nextUp(after: current)
                } else {
                    current = scale.nextDown(before: current)
                }
            }
            return current
        }
        
        var sequence: [Pitch] = [anchored]
        var current = anchored
        var deltaIndex = 0
        
        // Phase 1: ascend, cycling the deltas as given. The first landing
        // outside the bounds (either side) is NOT appended and ends the
        // phase — without advancing the index, so phase 2 begins with the
        // same delta negated (the natural retrograde turnaround).
        phaseLoop: while true {
            let landing = step(current, deltas[deltaIndex])
            guard low.midiNumber <= landing.midiNumber, landing.midiNumber <= high.midiNumber else {
                break phaseLoop
            }
            sequence.append(landing)
            current = landing
            deltaIndex = (deltaIndex + 1) % deltas.count
        }
        
        // Phase 2: descend, cycling the negated deltas from the index
        // that failed. Same bounds rule; the failing landing is not
        // appended.
        while true {
            let landing = step(current, -deltas[deltaIndex])
            guard low.midiNumber <= landing.midiNumber, landing.midiNumber <= high.midiNumber else {
                break
            }
            sequence.append(landing)
            current = landing
            deltaIndex = (deltaIndex + 1) % deltas.count
        }
        
        // Phase 3: stepwise return toward the anchored start, ending
        // exactly on its spelling (a descending approach on a
        // direction-spelled walk can land enharmonic — swap in the anchor).
        while current.midiNumber != anchored.midiNumber {
            current = current.midiNumber < anchored.midiNumber
                ? scale.nextUp(after: current)
                : scale.nextDown(before: current)
            sequence.append(current)
        }
        if current != anchored {
            sequence[sequence.count - 1] = anchored
        }
        
        return sequence
    }
}